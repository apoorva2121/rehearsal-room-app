#!/usr/bin/env python3
"""Build the on-phone edition from phone/index.html.

The published web page gets its <html><head> skeleton from claude.ai. The
copy that runs on the phone's own server needs one of its own, plus the
bits that make Chrome install it as a home-screen app: a manifest, icons,
and a service worker that keeps the whole app (page, data, figures) cached
on the phone, so the home-screen icon still opens when the Termux server is
not running.

Run:  python phone-local/build_phone.py
Then copy phone-local/* into the phone's RehearsalRoom folder.
"""
import hashlib, json, pathlib
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
TEAL, PAPER = (15, 95, 105), (255, 255, 255)

def icon(size):
    img = Image.new("RGB", (size, size), TEAL)
    d = ImageDraw.Draw(img)
    # a white reading plate with an R - the app's own look, shrunk to a glyph
    pad = int(size * 0.18)
    d.rounded_rectangle([pad, pad, size - pad, size - pad], radius=int(size * 0.07), fill=PAPER)
    font = None
    for name in ("georgiab.ttf", "SitkaVF.ttf", "cambriab.ttf", "times.ttf"):
        p = pathlib.Path("C:/Windows/Fonts") / name
        if p.exists():
            font = ImageFont.truetype(str(p), int(size * 0.46)); break
    font = font or ImageFont.load_default()
    box = d.textbbox((0, 0), "R", font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    d.text(((size - w) / 2 - box[0], (size - h) / 2 - box[1]), "R", font=font, fill=TEAL)
    return img

SW = r'''// Rehearsal Room service worker - generated by build_phone.py, do not edit.
const CACHE = 'rehearsal-room-__VERSION__';

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    let list = [];
    try { list = await (await fetch('precache.json', { cache: 'no-store' })).json(); } catch (err) {}
    let i = 0;
    const worker = async () => {
      while (i < list.length) {
        const url = list[i++];
        try { const r = await fetch(url, { cache: 'no-store' }); if (r.ok) await cache.put(url, r); } catch (err) {}
      }
    };
    await Promise.all([worker(), worker(), worker(), worker()]);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('rehearsal-room-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  e.respondWith((async () => {
    try {
      const net = await fetch(e.request);
      if (net.ok && url.pathname !== '/precache.json') {
        const cache = await caches.open(CACHE);
        cache.put(e.request, net.clone());
      }
      return net;
    } catch (err) {
      const hit = await caches.match(e.request, { ignoreSearch: true });
      if (hit) return hit;
      throw err;
    }
  })());
});
'''

for s in (192, 512):
    icon(s).save(HERE / "icons" / f"icon-{s}.png")

(HERE / "manifest.json").write_text(json.dumps({
    "name": "Rehearsal Room",
    "short_name": "Rehearsal",
    "description": "Interview questions, one at a time.",
    "start_url": "/",
    "scope": "/",
    "display": "standalone",
    "orientation": "portrait",
    "background_color": "#e7eaea",
    "theme_color": "#dadfdf",
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any maskable"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"},
    ],
}, indent=2), encoding="utf-8")

src = (ROOT / "phone" / "index.html").read_text(encoding="utf-8")
cut = src.index("</style>") + len("</style>")
head, body = src[:cut], src[cut:]

# The online half (transcribe, grade, cross-question) is shared with the
# laptop edition and inlined here, so the on-phone page stays a single
# self-contained file that the service worker can cache whole.
ai_js = (ROOT / "assets" / "ai-client.js").read_text(encoding="utf-8")
wrapped = (
    '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
    '<meta name="theme-color" content="#dadfdf">\n'
    '<link rel="manifest" href="manifest.json">\n'
    '<link rel="icon" href="icons/icon-192.png">\n'
    '<link rel="apple-touch-icon" href="icons/icon-192.png">\n'
    + head + "\n</head>\n<body>"
    + "<script>\n" + ai_js + "\n</script>\n" + body +
    "\n<script>if ('serviceWorker' in navigator) navigator.serviceWorker.register('sw.js').catch(function(){});</script>"
    "\n</body>\n</html>\n")
(HERE / "index.html").write_text(wrapped, encoding="utf-8")

# The service worker. Network first while the server is up, so a rebuild is
# seen at once; the cache when it is not, so the icon always opens. On
# install it pulls everything in precache.json (page, data, every figure).
# /api/* is never touched - the page handles a missing server itself.
shell = ["./", "index.html", "manifest.json", "icons/icon-192.png", "icons/icon-512.png"]
content = sorted(p.relative_to(ROOT).as_posix()
                 for d in ("data", "figures") for p in (ROOT / d).rglob("*") if p.is_file())
stamp = hashlib.sha1(("\n".join("%s:%d" % (f, (ROOT / f).stat().st_size) for f in content)
                      + wrapped).encode("utf-8")).hexdigest()[:12]
(HERE / "precache.json").write_text(json.dumps(shell + content), encoding="utf-8")
(HERE / "sw.js").write_text(SW.replace("__VERSION__", stamp), encoding="utf-8")
print("built: index.html, manifest.json, sw.js (v%s, %d files precached), precache.json, icons/"
      % (stamp, len(shell) + len(content)))
